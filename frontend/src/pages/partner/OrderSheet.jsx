import { ErrorBox, Loading, Modal, fmtDate, fmtDateTime, useApi } from "../../components/ui";

// Printable order sheet = legacy "Download Prescription" (lab) / prescription print (pharmacy)
export default function OrderSheet({ orderId, onClose }) {
  const { data, loading, error, reload } = useApi(`partner/orders/${orderId}/sheet`);
  return (
    <Modal open title={`Order #${orderId}`} onClose={onClose} xl>
      {loading && !data ? <Loading /> : error ? <ErrorBox onRetry={reload} /> : (() => {
        const lab = data.kind === "lab"; const a = data.appointment || {}; const p = data.partner || {};
        return (<>
          <div className="row no-print" style={{ justifyContent: "flex-end" }}><button className="btn primary sm" onClick={() => window.print()}>Print / Save PDF</button></div>
          <article className="casefile">
            <header className="cf-head"><div><h2>{p.name}</h2><p>{[p.address, p.city].filter(Boolean).join(", ")} · {p.land_phone}</p></div>
              <div className="cf-title"><b>{lab ? "LAB ORDER" : "PRESCRIPTION"}</b><span>#{orderId} · {fmtDateTime(data.date)}</span></div></header>
            <div className="cf-grid">
              <div><span>Patient</span><b>{a.fullname}</b><small>{a.permanentid}{a.email && a.email !== "NA" ? ` · ${a.email}` : ""}</small></div>
              <div><span>Doctor</span><b>{a.doctor_name}</b><small>{a.deptname} · {a.hospital_name}</small></div>
              <div><span>Appointment</span><b>{a.appointmentid}</b><small>{fmtDate(a.date_of_booking)} · {a.time_of_booking}</small></div></div>
            <section className="cf-sec"><h4>{lab ? "Lab tests" : "Medicines"}</h4>
              <table><thead>{lab ? <tr><th>Test</th><th>Urgent</th><th>Repeat</th><th>Status</th></tr> : <tr><th>Medicine</th><th>Qty</th><th>Usage</th><th>Instructions</th><th>Duration</th><th>Status</th></tr>}</thead>
                <tbody>{data.items.map((i, n) => lab
                  ? <tr key={n}><td>{i.name}</td><td>{i.emergency ? "Yes" : "No"}</td><td>{i.repeat ? "Yes" : "No"}</td><td>{i.status}</td></tr>
                  : <tr key={n}><td>{i.name}{i.repeat ? " (repeat)" : ""}</td><td>{i.quantity}</td><td>{i.usage}</td><td>{i.instructions}</td><td>{i.duration}</td><td>{i.status}</td></tr>)}</tbody></table></section>
            <footer className="cf-foot">Generated by Cobalt EHR · {new Date().toLocaleString()}</footer>
          </article></>);
      })()}
    </Modal>
  );
}
